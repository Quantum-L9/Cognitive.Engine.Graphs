#!/usr/bin/env python3
"""
--- L9_META ---
l9_schema: 1
origin: engine-specific
engine: graph
layer: [tools]
tags: [tools, domain-spec, json-schema, contracts]
owner: engine-team
status: active
--- /L9_META ---

Export the DomainSpec contract as a versioned JSON Schema artifact.

    python tools/export_domain_spec_schema.py           # write the artifact
    python tools/export_domain_spec_schema.py --check   # exit 1 and show the drift

The artifact is ``DomainSpec.model_json_schema()`` (validation mode, JSON Schema
2020-12) with every object key sorted, preceded by the L9_META header, the
dialect, a ``$id`` carrying ``DOMAIN_SPEC_SCHEMA_VERSION`` and a provenance
``$comment``. It is derived: ``engine/config/schema.py`` stays the authority,
and the schema states structure only, not the loader's admission rules.

Layout follows the repository's JSON formatter (Biome, biome.json: two-space
indent, a scalar array on one line when the line fits in 100 columns), so a
formatter run leaves the artifact byte-identical.
"""

from __future__ import annotations

import argparse
import difflib
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from engine.config.domain_spec_schema_version import DOMAIN_SPEC_SCHEMA_VERSION
from engine.config.schema import DomainSpec
from tools.l9_meta_injector import ENGINE_ID, FILE_REGISTRY, format_json_meta

ARTIFACT_RELPATH = "docs/contracts/data/models/domain-spec.schema.json"
ARTIFACT_PATH = REPO_ROOT / ARTIFACT_RELPATH
SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"
SCHEMA_ID_BASE = "https://github.com/Quantum-L9/Cognitive.Engine.Graphs/docs/contracts/data/models/domain-spec"
PROVENANCE = (
    "Generated by tools/export_domain_spec_schema.py from engine.config.schema.DomainSpec. "
    "Do not edit; change engine/config/schema.py, bump "
    "engine/config/domain_spec_schema_version.py and regenerate."
)
LINE_WIDTH = 100
_DIFF_LINES = 40


def schema_id(version: str = DOMAIN_SPEC_SCHEMA_VERSION) -> str:
    """Return the ``$id`` of the schema at *version*."""
    return f"{SCHEMA_ID_BASE}/{version}/domain-spec.schema.json"


def _sorted(value: Any) -> Any:
    """Sort object keys at every depth; array order is meaningful and kept."""
    if isinstance(value, dict):
        return {key: _sorted(value[key]) for key in sorted(value)}
    if isinstance(value, list):
        return [_sorted(item) for item in value]
    return value


def _header() -> dict[str, Any]:
    """Return the artifact's L9_META header from its FILE_REGISTRY entry."""
    for meta in FILE_REGISTRY:
        if meta.path == ARTIFACT_RELPATH:
            return format_json_meta(meta, ENGINE_ID)
    msg = f"{ARTIFACT_RELPATH} is not registered in tools/l9_meta_injector.py FILE_REGISTRY"
    raise RuntimeError(msg)


def build_schema() -> dict[str, Any]:
    """Return the artifact as a mapping in its published key order."""
    body = _sorted(DomainSpec.model_json_schema())
    return {
        "_l9_meta": _header(),
        "$schema": SCHEMA_DIALECT,
        "$id": schema_id(),
        "$comment": PROVENANCE,
        **body,
    }


def _render(value: Any, level: int, lead: int, trailing: int) -> str:
    """Render *value*; *lead*/*trailing* are the columns around it on its first line."""
    pad = "  " * (level + 1)
    if isinstance(value, dict) and value:
        last = len(value) - 1
        members = []
        for index, (key, item) in enumerate(value.items()):
            prefix = f"{pad}{json.dumps(key)}: "
            members.append(prefix + _render(item, level + 1, len(prefix), int(index != last)))
        return "{\n" + ",\n".join(members) + "\n" + "  " * level + "}"
    if isinstance(value, list) and value:
        if not any(isinstance(item, dict | list) and item for item in value):
            inline = "[" + ", ".join(json.dumps(item) for item in value) + "]"
            if lead + len(inline) + trailing <= LINE_WIDTH:
                return inline
        last = len(value) - 1
        items = [pad + _render(item, level + 1, len(pad), int(index != last)) for index, item in enumerate(value)]
        return "[\n" + ",\n".join(items) + "\n" + "  " * level + "]"
    return json.dumps(value)


def render() -> str:
    """Return the exact artifact text, trailing newline included."""
    return _render(build_schema(), 0, 0, 0) + "\n"


def check(artifact: Path = ARTIFACT_PATH) -> list[str]:
    """Return the drift between *artifact* and a fresh export; empty when equal."""
    expected = render()
    if not artifact.is_file():
        return [f"{artifact}: missing"]
    actual = artifact.read_text(encoding="utf-8")
    if actual == expected:
        return []
    diff = list(
        difflib.unified_diff(
            actual.splitlines(), expected.splitlines(), f"{artifact} (committed)", "fresh export", lineterm="", n=1
        )
    )
    return diff or [f"{artifact}: differs from a fresh export in line endings or the trailing newline only"]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export the DomainSpec contract as a versioned JSON Schema artifact.")
    parser.add_argument("--check", action="store_true", help="compare the artifact with a fresh export; write nothing")
    parser.add_argument("--artifact", type=Path, default=ARTIFACT_PATH, help="artifact path (default: %(default)s)")
    args = parser.parse_args(argv)

    if args.check:
        drift = check(args.artifact)
        if drift:
            print(f"DRIFT: {args.artifact} does not match engine.config.schema.DomainSpec", file=sys.stderr)
            print("\n".join(drift[:_DIFF_LINES]), file=sys.stderr)
            if len(drift) > _DIFF_LINES:
                print(f"... {len(drift) - _DIFF_LINES} more diff lines", file=sys.stderr)
            print("Regenerate: python tools/export_domain_spec_schema.py", file=sys.stderr)
            return 1
        text = args.artifact.read_text(encoding="utf-8")
    else:
        text = render()
        args.artifact.write_text(text, encoding="utf-8")
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    print(f"{'OK' if args.check else 'WROTE'} {args.artifact} version={DOMAIN_SPEC_SCHEMA_VERSION} sha256={digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
